#!/usr/bin/env node
/**
 * Generates src/linter/generated/constraints.ts from spec/openapi.json.
 *
 * Walks every POST endpoint whose request body is discriminated by a `model`
 * property (either a oneOf with one variant per model, or a single schema with
 * a const model) and extracts the scalar constraints a linter can check
 * statically: enums, consts, numeric ranges, and string lengths.
 *
 * Refresh the spec with:
 *   curl -sL -o spec/openapi.json https://raw.githubusercontent.com/runwayml/openapi/next/openapi.json
 *   npm run generate:constraints
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const spec = JSON.parse(readFileSync(join(root, 'spec', 'openapi.json'), 'utf8'));

const SCALAR_KEYS = ['enum', 'const', 'type', 'minimum', 'maximum', 'minLength', 'maxLength'];

function toResourceName(path) {
  const slug = path.replace(/^\/v1\//, '');
  return slug.replace(/_([a-z])/g, (_, c) => c.toUpperCase());
}

function extractConstraint(schema) {
  const constraint = {};
  for (const key of SCALAR_KEYS) {
    if (schema[key] !== undefined) constraint[key] = schema[key];
  }
  // Nested objects, arrays, and anyOf unions have no scalar constraints we
  // can check statically; an empty constraint still marks the param as known.
  if (constraint.type === 'object' || constraint.type === 'array') return {};
  return constraint;
}

function extractVariant(variant) {
  const params = {};
  for (const [name, schema] of Object.entries(variant.properties ?? {})) {
    if (name === 'model') continue;
    params[name] = extractConstraint(schema);
  }
  return { required: variant.required ?? [], params };
}

function modelName(variant) {
  const model = variant.properties?.model;
  if (!model) return null;
  if (model.const !== undefined) return model.const;
  if (Array.isArray(model.enum) && model.enum.length === 1) return model.enum[0];
  return null;
}

const endpoints = {};
for (const [path, item] of Object.entries(spec.paths)) {
  const schema = item.post?.requestBody?.content?.['application/json']?.schema;
  if (!schema) continue;
  const models = {};
  for (const variant of schema.oneOf ?? [schema]) {
    const model = modelName(variant);
    if (model !== null) models[model] = extractVariant(variant);
  }
  if (Object.keys(models).length > 0) {
    endpoints[toResourceName(path)] = { path, models };
  }
}

const header = `// Generated by scripts/generate-constraints.mjs from spec/openapi.json — do not edit.
// Spec version: ${spec.info?.version ?? 'unknown'}
import type { EndpointConstraints } from '../types.js';

export const ENDPOINTS: Readonly<Record<string, EndpointConstraints>> = `;

writeFileSync(
  join(root, 'src', 'linter', 'generated', 'constraints.ts'),
  `${header}${JSON.stringify(endpoints, null, 2)};\n`,
);

const modelCount = Object.values(endpoints).reduce((n, e) => n + Object.keys(e.models).length, 0);
console.log(`Wrote ${Object.keys(endpoints).length} endpoints, ${modelCount} model variants.`);
